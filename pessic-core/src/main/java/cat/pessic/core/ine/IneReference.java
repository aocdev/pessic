package cat.pessic.core.ine;

import cat.pessic.core.budget.BudgetConfig;
import cat.pessic.core.budget.Category;
import cat.pessic.core.common.Money;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.EnumMap;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * INE reference spending (Encuesta de Presupuestos Familiares, COICOP 2018) bundled with the app
 * in {@code /ine/epf.tsv}, generated by {@code tools/ine/fetch_epf.py}.
 *
 * <p>The expectation for a category is the mean of what INE reports, per household and month, for
 * households of the same type, the same number of members and the same net monthly income band.
 * Breakdowns that are unknown for the profile, or that INE does not publish for a category, are left
 * out of the mean.
 */
public final class IneReference {

    /** INE figures for one category, already converted to euros per month. Nullable parts were not available. */
    public record Expectation(Category category, BigDecimal monthly, BigDecimal byType, BigDecimal bySize,
                              BigDecimal byIncome) {}

    private record Band(int min, Integer max, String label) {}

    private static IneReference defaultInstance;

    private final int year;
    private final Map<String, Map<Category, BigDecimal>> annual = new HashMap<>(); // "type:3" -> group -> €/year
    private final List<Band> bands = new ArrayList<>();

    private IneReference(int year) {
        this.year = year;
    }

    /** The data shipped with the app. */
    public static synchronized IneReference bundled() {
        if (defaultInstance == null) {
            try (InputStream in = IneReference.class.getResourceAsStream("/ine/epf.tsv")) {
                if (in == null) throw new IllegalStateException("Missing /ine/epf.tsv");
                defaultInstance = parse(in);
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }
        return defaultInstance;
    }

    static IneReference parse(InputStream in) throws IOException {
        int year = 0;
        List<String[]> rows = new ArrayList<>();
        try (BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            for (String line; (line = r.readLine()) != null; ) {
                if (line.startsWith("# year\t")) year = Integer.parseInt(line.substring(7).strip());
                if (line.isBlank() || line.startsWith("#") || line.startsWith("breakdown\t")) continue;
                rows.add(line.split("\t", -1));
            }
        }
        IneReference ref = new IneReference(year);
        for (String[] f : rows) {
            // breakdown key label income_min income_max group annual_eur
            Category c = Category.ofCode(f[5]);
            ref.annual.computeIfAbsent(f[0] + ":" + f[1], k -> new EnumMap<>(Category.class))
                    .put(c, new BigDecimal(f[6]));
            if (f[0].equals("income") && !f[1].equals("total")
                    && ref.bands.stream().noneMatch(b -> b.label.equals(f[2]))) {
                ref.bands.add(new Band(Integer.parseInt(f[3]), f[4].isEmpty() ? null : Integer.parseInt(f[4]), f[2]));
            }
        }
        ref.bands.sort((a, b) -> Integer.compare(a.min, b.min));
        return ref;
    }

    /** Reference year of the survey, e.g. 2025. */
    public int year() {
        return year;
    }

    /** INE's label for the income band containing a net monthly income, e.g. "De 2.000 a 2.499 euros". */
    public Optional<String> incomeBand(BigDecimal monthlyIncome) {
        return band(monthlyIncome).map(Band::label);
    }

    private Optional<Band> band(BigDecimal monthlyIncome) {
        if (monthlyIncome == null || monthlyIncome.signum() <= 0) return Optional.empty();
        Band found = null;
        for (Band b : bands) if (monthlyIncome.compareTo(BigDecimal.valueOf(b.min)) >= 0) found = b;
        return Optional.ofNullable(found);
    }

    public Expectation expected(Category c, int household, Integer members, BigDecimal monthlyIncome) {
        BigDecimal byType = monthly("type:" + household, c);
        BigDecimal bySize = members == null ? null
                : monthly("size:" + Math.max(1, Math.min(Catalog.MAX_MEMBERS, members)), c);
        BigDecimal byIncome = band(monthlyIncome).map(b -> monthly("income:" + b.min, c)).orElse(null);
        BigDecimal sum = BigDecimal.ZERO;
        int n = 0;
        for (BigDecimal v : new BigDecimal[]{byType, bySize, byIncome}) {
            if (v != null) {
                sum = sum.add(v);
                n++;
            }
        }
        BigDecimal mean = n == 0 ? BigDecimal.ZERO : Money.round(Money.divide(sum, n));
        return new Expectation(c, mean, round(byType), round(bySize), round(byIncome));
    }

    public Map<Category, Expectation> expected(BudgetConfig cfg) {
        Map<Category, Expectation> out = new EnumMap<>(Category.class);
        for (Category c : Category.ALL) out.put(c, expected(c, cfg.household(), cfg.members(), cfg.income()));
        return out;
    }

    private BigDecimal monthly(String key, Category c) {
        Map<Category, BigDecimal> m = annual.get(key);
        BigDecimal v = m == null ? null : m.get(c);
        return v == null ? null : Money.divide(v, 12);
    }

    private static BigDecimal round(BigDecimal v) {
        return v == null ? null : Money.round(v);
    }
}
